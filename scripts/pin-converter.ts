#!/usr/bin/env bun
// Moves the bc-mdc-converter pin: bun scripts/pin-converter.ts v0.2.0
// Reads the release's asset digests (sha256) from the GitHub API, cross-checks them against the
// release's SHA256SUMS, and rewrites src/core/converter-pin.ts.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const REPO = "SShadowS/bc-mdc-converter";
const tag = process.argv[2];
if (!tag?.startsWith("v")) {
  console.error("usage: bun scripts/pin-converter.ts v<version>");
  process.exit(2);
}
const res = await fetch(`https://api.github.com/repos/${REPO}/releases/tags/${tag}`, { headers: { accept: "application/vnd.github+json" } });
if (!res.ok) throw new Error(`release ${tag}: HTTP ${res.status}`);
const release = (await res.json()) as { assets: { name: string; size: number; digest?: string }[] };
const keys: Record<string, string> = {
  "bc-mdc-converter-windows-x64.exe": "win32-x64",
  "bc-mdc-converter-windows-arm64.exe": "win32-arm64",
  "bc-mdc-converter-linux-x64": "linux-x64",
  "bc-mdc-converter-linux-arm64": "linux-arm64",
  "bc-mdc-converter-macos-x64": "darwin-x64",
  "bc-mdc-converter-macos-arm64": "darwin-arm64",
};
const assets: Record<string, { name: string; sha256: string; size: number }> = {};
for (const a of release.assets) {
  const key = keys[a.name];
  if (!key) continue;
  if (!a.digest?.startsWith("sha256:")) throw new Error(`${a.name} has no sha256 digest`);
  assets[key] = { name: a.name, sha256: a.digest.slice(7), size: a.size };
}
for (const name of Object.keys(keys)) if (!Object.values(assets).some((a) => a.name === name)) throw new Error(`${tag} has no ${name}`);

// Cross-check against the release's own SHA256SUMS ("<hex>  <name>" lines).
const sumsRes = await fetch(`https://github.com/${REPO}/releases/download/${tag}/SHA256SUMS`, { redirect: "follow" });
if (!sumsRes.ok) throw new Error(`${tag} SHA256SUMS: HTTP ${sumsRes.status}`);
const sums = new Map<string, string>();
for (const line of (await sumsRes.text()).split(/\r?\n/)) {
  const m = /^([0-9a-fA-F]{64})\s+\*?(.+?)\s*$/.exec(line);
  if (m) sums.set(m[2]!, m[1]!.toLowerCase());
}
for (const a of Object.values(assets)) {
  const listed = sums.get(a.name);
  if (listed !== a.sha256) throw new Error(`${a.name}: GitHub digest ${a.sha256} differs from SHA256SUMS ${listed ?? "(missing)"}`);
}

const file = join(import.meta.dir, "../src/core/converter-pin.ts");
const body = Object.entries(assets)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, a]) => `    "${key}": { name: "${a.name}", sha256: "${a.sha256}", size: ${a.size} },`)
  .join("\n");
writeFileSync(file, `// GENERATED by scripts/pin-converter.ts from the bc-mdc-converter GitHub release; re-run it to move the pin.
import type { ToolPin } from "./tool-binary";

export const CONVERTER_PIN: ToolPin = {
  version: "${tag.slice(1)}",
  assets: {
${body}
  },
};
`);
console.log(`pinned bc-mdc-converter ${tag.slice(1)}: ${Object.keys(assets).join(", ")}`);
