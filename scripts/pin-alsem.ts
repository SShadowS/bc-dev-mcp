#!/usr/bin/env bun
// Moves the al-sem pin: bun scripts/pin-alsem.ts v1.7.1
// Reads the release's asset digests (sha256) from the GitHub API and rewrites src/core/alsem-pin.ts.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const tag = process.argv[2];
if (!tag?.startsWith("v")) {
  console.error("usage: bun scripts/pin-alsem.ts v<version>");
  process.exit(2);
}
const res = await fetch(`https://api.github.com/repos/SShadowS/al-sem/releases/tags/${tag}`, { headers: { accept: "application/vnd.github+json" } });
if (!res.ok) throw new Error(`release ${tag}: HTTP ${res.status}`);
const release = (await res.json()) as { assets: { name: string; size: number; digest?: string }[] };
const keys: Record<string, string> = { "alsem-windows-x64.exe": "win32-x64", "alsem-linux-x64": "linux-x64" };
const assets: Record<string, { name: string; sha256: string; size: number }> = {};
for (const a of release.assets) {
  const key = keys[a.name];
  if (!key) continue;
  if (!a.digest?.startsWith("sha256:")) throw new Error(`${a.name} has no sha256 digest`);
  assets[key] = { name: a.name, sha256: a.digest.slice(7), size: a.size };
}
for (const name of Object.keys(keys)) if (!Object.values(assets).some((a) => a.name === name)) throw new Error(`${tag} has no ${name}`);

const file = join(import.meta.dir, "../src/core/alsem-pin.ts");
const body = Object.entries(assets)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, a]) => `    "${key}": { name: "${a.name}", sha256: "${a.sha256}", size: ${a.size} },`)
  .join("\n");
writeFileSync(file, `// GENERATED by scripts/pin-alsem.ts from the al-sem GitHub release; re-run it to move the pin.
export interface AlSemPin {
  version: string;
  /** Keyed \`\${process.platform}-\${process.arch}\`. */
  assets: Record<string, { name: string; sha256: string; size: number }>;
}

export const ALSEM_PIN: AlSemPin = {
  version: "${tag.slice(1)}",
  assets: {
${body}
  },
};
`);
console.log(`pinned al-sem ${tag.slice(1)}: ${Object.keys(assets).join(", ")}`);
