// Embeds skills/*/SKILL.md into src/mcp/skills.generated.ts so the single-file
// dist bundle and compiled exe can serve them over MCP (final SEP-2640: skills/list,
// skills/get, resources/read). Digest and size are precomputed from the exact UTF-8 bytes served.
// Frontmatter constraints: single-line `key: value` lines (kept verbatim, surrounding quotes
// stripped); the `name`/`description` rules live in src/core/skill-frontmatter.ts.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { SkillFrontmatterSchema } from "../src/core/skill-frontmatter";

export interface EmbeddedSkill {
  name: string;
  description: string;
  uri: string;
  mimeType: string;
  text: string;
  /** Every frontmatter field, unchanged (SEP-2640 requires all fields in the skill entry). */
  frontmatter: Record<string, string>;
  /** `sha256:<hex>` of the UTF-8 bytes of `text`. */
  digest: string;
  /** Byte length of `text` as UTF-8. */
  size: number;
}

function parseFrontmatter(skill: string, block: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of block.split("\n")) {
    if (line.trim() === "") continue;
    const m = /^([A-Za-z0-9_-]+):\s*(.*?)\s*$/.exec(line);
    if (!m) throw new Error(`${skill}/SKILL.md: frontmatter line is not single-line "key: value": ${line}`);
    out[m[1]!] = m[2]!.replace(/^(["'])(.*)\1$/, "$2");
  }
  return out;
}

export async function collectSkills(skillsDir: string): Promise<EmbeddedSkill[]> {
  const out: EmbeddedSkill[] = [];
  for (const entry of await readdir(skillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const raw = await readFile(join(skillsDir, entry.name, "SKILL.md"), "utf8");
    const text = raw.replace(/\r\n/g, "\n");
    const fm = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
    if (!fm) throw new Error(`${entry.name}/SKILL.md: missing YAML frontmatter`);
    const frontmatter = parseFrontmatter(entry.name, fm[1]!);
    const { name, description } = frontmatter;
    if (!name || name !== entry.name) throw new Error(`${entry.name}/SKILL.md: frontmatter name must equal directory name`);
    const parsed = SkillFrontmatterSchema.safeParse({ name, description: description ?? "" });
    if (!parsed.success) throw new Error(`${name}: ${parsed.error.issues[0]!.message}`);
    const bytes = Buffer.from(text, "utf8");
    out.push({
      name,
      description: parsed.data.description,
      uri: `skill://${name}/SKILL.md`,
      mimeType: "text/markdown",
      text,
      frontmatter,
      digest: `sha256:${createHash("sha256").update(bytes).digest("hex")}`,
      size: bytes.length,
    });
  }
  out.sort((a, b) => a.name.localeCompare(b.name));
  if (out.length === 0) throw new Error(`no skills found under ${skillsDir}`);
  return out;
}

export function renderModule(skills: EmbeddedSkill[]): string {
  return (
    "// GENERATED by scripts/embed-skills.ts — do not edit.\n" +
    "// Edit skills/*/SKILL.md and run: bun run embed-skills\n" +
    "export interface EmbeddedSkill {\n  name: string;\n  description: string;\n  uri: string;\n  mimeType: string;\n  text: string;\n" +
    "  frontmatter: Record<string, string>;\n  digest: string;\n  size: number;\n}\n\n" +
    `export const skills: EmbeddedSkill[] = ${JSON.stringify(skills, null, 2)};\n`
  );
}

if (import.meta.main) {
  const repoRoot = join(import.meta.dir, "..");
  const skills = await collectSkills(join(repoRoot, "skills"));
  await writeFile(join(repoRoot, "src", "mcp", "skills.generated.ts"), renderModule(skills));
  console.log(`embedded ${skills.length} skills -> src/mcp/skills.generated.ts`);
}
